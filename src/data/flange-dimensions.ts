/** SO/SW/THD ring thickness: same as WN for 150/300, WN − 3.2 mm for 600+ */
export function soThickness(cls: number, tWn: number): number {
  return cls >= 600 ? Math.max(11.2, tWn - 3.2) : tWn;
}

/** Get NPS_LIST index for an NPS value, -1 if not present */
export function npsIndex(nps: number): number {
  return NPS_LIST.findIndex((n) => n.nps === nps);
}
