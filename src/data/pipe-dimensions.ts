/** Get pipe NPS info by nps value */
export function getPipeNps(nps: number): PipeNps | undefined {
  return PIPE_DATA.find(p => p.nps === nps);
}

/** Get available schedules for a given NPS (excluding zero-wall entries) */
export function getAvailableSchedules(nps: number): PipeSchedule[] {
  const pipe = getPipeNps(nps);
  if (!pipe) return [];
  return pipe.schedules.filter(s => s.wallThickness > 0);
}

/** Get wall thickness for a specific NPS + schedule */
export function getWallThickness(nps: number, scheduleId: string): number {
  const pipe = getPipeNps(nps);
  if (!pipe) return 0;
  const sched = pipe.schedules.find(s => s.id === scheduleId);
  return sched ? sched.wallThickness : 0;
}
